class OV_i18n {

    /**
     * Cargar el dominio de texto del plugin para traducciones.
     */
    public function load_plugin_textdomain() {
        load_plugin_textdomain(
            'ov-booking-system',
            false,
            dirname(dirname(plugin_basename(__FILE__))) . '/languages/'
        );

        add_filter('gettext', array($this, 'fallback_gettext'), 20, 3);
    }

    /**
     * Locale simplificado basado en el idioma activo de WordPress.
     */
    public static function get_language() {
        $locale = function_exists('determine_locale') ? determine_locale() : get_locale();
        $locale = strtolower((string) $locale);

        if (strpos($locale, 'it') === 0) {
            return 'it';
        }

        if (strpos($locale, 'pt') === 0) {
            return 'pt';
        }

        if (strpos($locale, 'en') === 0) {
            return 'en';
        }

        return 'es';
    }

    /**
     * Locale para JavaScript Intl/toLocaleDateString.
     */
    public static function get_js_locale() {
        $lang = self::get_language();

        $map = array(
            'es' => 'es-ES',
            'en' => 'en-US',
            'it' => 'it-IT',
            'pt' => 'pt-BR',
        );

        return isset($map[$lang]) ? $map[$lang] : 'es-ES';
    }

    /**
     * Traducir texto usando el diccionario interno.
     */
    public static function translate($text) {
        $lang = self::get_language();
        $dict = array_replace_recursive(self::dictionary(), self::admin_dictionary());

        if ($lang === 'es') {
            return $text;
        }

        return isset($dict[$lang][$text]) ? $dict[$lang][$text] : $text;
    }

    /**
     * Fallback para textos PHP que ya usan funciones __(), _e(), esc_html__(), etc.
     */
    public function fallback_gettext($translation, $text, $domain) {
        if ($domain !== 'ov-booking-system') {
            return $translation;
        }

        $fallback = self::translate($text);
        return $fallback !== $text ? $fallback : $translation;
    }

